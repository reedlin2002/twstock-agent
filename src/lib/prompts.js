// 把 Google News 抓到的新聞清單組成提示文字（標題＋日期＋來源，無全文）
export const buildNewsBlock = (newsItems) => {
  if (!Array.isArray(newsItems) || newsItems.length === 0) {
    return '以下是用 Google News 依此台股抓取的近期新聞清單：（這次沒有抓到相關新聞，消息面請寫「資料不足」，基本面／產業改以既有知識謹慎整理並標「非即時，請查證」。）';
  }
  const lines = newsItems.map((n, i) => {
    const date = n.date ? `（${n.date}）` : '';
    const source = n.source ? ` — ${n.source}` : '';
    return `${i + 1}. ${n.title}${date}${source}`;
  });
  return `以下是用 Google News 依此台股抓取的近期新聞標題清單（由新到舊，僅標題與來源、無全文）：\n${lines.join('\n')}`;
};

